export function t(lang: LanguageCode, key: keyof typeof translations['en'], params?: Record<string, string>): string {
  let text = translations[lang]?.[key] || translations['en'][key];
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, v);
    }
  }
  return text;
}
